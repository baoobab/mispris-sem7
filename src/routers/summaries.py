def apply_summaries(app: FastAPI) -> None:
    """Проставить заголовки и описания всем операциям; падает, если для операции нет перевода."""
    missing = []
    for route in app.routes:
        if not isinstance(route, APIRoute):
            continue
        name = route.endpoint.__name__
        if name not in SUMMARIES:
            missing.append(name)
            continue
        route.summary, description = SUMMARIES[name]
        route.description = description
    if missing:
        raise RuntimeError(f"Нет русского заголовка для операций: {missing}")
